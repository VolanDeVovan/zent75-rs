/// Nonlinear step of the IIR filter, `T(d)` for `d = −512..511` (stock table at `0x89708`).
pub const fn iir_step(d: i32) -> i32 {
    if d == -512 {
        return 0; // table entry 0 (unreachable: |d| > 323 bypasses the table)
    }
    let a = d.abs();
    let r = if a < 64 {
        a / 8 + 1
    } else if a < 128 {
        a / 4
    } else {
        a / 2
    };
    if d > 0 { r } else { -r }
}
